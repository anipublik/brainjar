#!/usr/bin/env python3
"""Rebuild notes/INDEX.md, people/INDEX.md and projects/INDEX.md
from each file's frontmatter. --check exits 1 if any index is stale."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDERS = ["notes", "people", "projects"]


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    head = text[4:].split("\n---", 1)[0]
    pairs = (line.split(":", 1) for line in head.splitlines() if ":" in line)
    return {k.strip(): v.strip() for k, v in pairs}


def render(folder):
    rows = []
    for f in sorted((ROOT / folder).glob("*.md")):
        if f.name == "INDEX.md":
            continue
        meta = frontmatter(f)
        desc = meta.get("description", "(no description)")
        extra = f" [{meta['status']}]" if "status" in meta else ""
        rows.append(f"- {f.name}{extra}: {desc}")
    head = f"# {folder}/ index\n\nGenerated by scripts/build_index.py. Do not edit by hand.\n\n"
    return head + ("\n".join(rows) or "- (empty)") + "\n"


def main(check=False):
    stale = []
    for folder in FOLDERS:
        (ROOT / folder).mkdir(exist_ok=True)
        idx, new = ROOT / folder / "INDEX.md", render(folder)
        if not idx.exists() or idx.read_text(encoding="utf-8") != new:
            stale.append(str(idx.relative_to(ROOT)))
            if not check:
                idx.write_text(new, encoding="utf-8")
    if check and stale:
        sys.exit("stale index: " + ", ".join(stale) + " (run scripts/build_index.py)")


if __name__ == "__main__":
    main(check="--check" in sys.argv)
